// Builds the README (for GitHub) and a local preview page from the same layout.
// The README uses <picture> so GitHub picks dark/light and desktop/mobile tiles.

const MOBILE = '(max-width: 600px)';

/**
 * forced = undefined → real README with <picture> switching.
 * forced = { theme, size } → plain <img> of one variant (local preview).
 */
function picture(base, name, alt, opts, forced) {
  const { mobile = true, width = '100%', height } = opts;
  const size = height ? `height="${height}"` : `width="${width}"`;
  const f = (sz, th) => `${base}${name}${mobile && sz === 'm' ? '-m' : ''}-${th}.svg`;
  if (forced) return `<img alt="${alt}" src="${f(forced.size, forced.theme)}" ${size}>`;
  const src = [];
  if (mobile) {
    src.push(`<source media="${MOBILE} and (prefers-color-scheme: dark)" srcset="${f('m', 'dark')}">`);
    src.push(`<source media="${MOBILE}" srcset="${f('m', 'light')}">`);
  }
  src.push(`<source media="(prefers-color-scheme: dark)" srcset="${f('d', 'dark')}">`);
  return `<picture>${src.join('')}<img alt="${alt}" src="${f('d', 'light')}" ${size}></picture>`;
}

const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

export function layout(p, base, forced) {
  const pic = (name, alt, opts = {}) => picture(base, name, attr(alt), opts, forced);
  const out = [];
  out.push(pic('hero', `${p.eyebrow}. ${p.headline.join(' ')} ${p.blurb}`));
  out.push('');
  const links = p.links.filter((l) => l.url);
  out.push(`<p>${links.map((l) => `<a href="${attr(l.url)}">${pic(`btn-${l.id}`, l.label, { mobile: false, height: 44 })}</a>`).join('&nbsp;')}</p>`);
  out.push('');
  if (p.now?.name && !p.now.name.startsWith('[')) {
    out.push(`<a href="${attr(p.now.url)}">${pic('now', `Now cooking: ${p.now.name} — ${p.now.note}`)}</a>`);
    out.push('<br><br>');
  }
  out.push('');
  out.push(pic('stack', `What's in it: ${p.layers.map((l) => `${l.layer} — ${(l.chips ?? []).join(', ')}`).join('; ')}`));
  out.push('');
  out.push(pic('menu', 'The menu: featured projects'));
  const cards = p.projects.map((pr, i) => ({
    url: `https://github.com/${p.login}/${pr.repo}`,
    name: `card-${String(i + 1).padStart(2, '0')}`,
    alt: `${pr.name}: ${pr.desc}`,
  }));
  cards.push({ url: p.fullMenuUrl, name: 'card-all', alt: 'Full menu: every repository' });
  out.push(cards.map((c) => `<a href="${attr(c.url)}">${pic(c.name, c.alt)}</a>`).join('<br>\n'));
  out.push('');
  out.push(pic('grill', 'Contribution graph for the last year'));
  out.push('');
  out.push(pic('facts', 'House specials and GitHub stats as a nutrition label'));
  out.push('');
  if (p.details?.length) out.push(pic('counter', 'Behind the counter'), '');
  for (const d of p.details ?? []) {
    out.push(`<details>\n<summary>${d.icon ? `${d.icon}&nbsp; ` : ''}<b>${attr(d.title)}</b> — ${attr(d.teaser)}</summary>\n\n${forced ? md(d.body) : d.body}\n\n</details>`);
    out.push('');
  }
  out.push('');
  out.push(pic('footer', 'Made to order, refreshed daily'));
  return out.join('\n');
}

export function readme(p) {
  const base = `https://raw.githubusercontent.com/${p.repo}/${p.outputBranch}/`;
  return `<!--
  Generated by scripts/build.mjs from profile.json — edit profile.json, not this file.
  The images live on the "${p.outputBranch}" branch and are rebuilt every night by .github/workflows/build.yml.
-->

${layout(p, base)}
`;
}

// Tiny markdown → HTML for the preview page's <details> bodies.
function md(s) {
  const inline = (t) => attr(t).replace(/\*\*(.+?)\*\*/g, '<b>$1</b>').replace(/_(.+?)_/g, '<i>$1</i>');
  const lines = s.split('\n');
  const html = [];
  let list = false;
  for (const l of lines) {
    if (l.startsWith('- ')) {
      if (!list) html.push('<ul>');
      list = true;
      html.push(`<li>${inline(l.slice(2))}</li>`);
    } else {
      if (list) html.push('</ul>');
      list = false;
      if (l.trim()) html.push(`<p>${inline(l)}</p>`);
    }
  }
  if (list) html.push('</ul>');
  return html.join('');
}

export function preview(p) {
  const views = [
    ['Desktop · dark', { theme: 'dark', size: 'd' }],
    ['Desktop · light', { theme: 'light', size: 'd' }],
    ['Phone · dark', { theme: 'dark', size: 'm' }],
    ['Phone · light', { theme: 'light', size: 'm' }],
  ];
  const sections = views
    .map(([name, f], i) => `<section data-i="${i}" class="${f.theme} ${f.size === 'm' ? 'phone' : ''}"${i ? ' hidden' : ''}><div class="col">${layout(p, './', f)}</div></section>`)
    .join('\n');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>${attr(p.login)} — README preview</title>
<style>
body{margin:0;font:14px/1.5 -apple-system,'Segoe UI',Helvetica,Arial,sans-serif}
nav{position:sticky;top:0;z-index:2;display:flex;gap:8px;padding:10px 16px;background:#222;flex-wrap:wrap}
nav button{font:inherit;padding:6px 12px;border-radius:6px;border:1px solid #555;background:#333;color:#eee;cursor:pointer}
nav button[aria-pressed=true]{background:#f2b33d;color:#111;border-color:#f2b33d}
section{min-height:100vh;padding:32px 16px}
section.dark{background:#0d1117;color:#e6edf3}section.light{background:#fff;color:#1f2328}
.col{max-width:880px;margin:0 auto}.phone .col{max-width:400px}
img{max-width:100%;vertical-align:top}p{margin:0 0 16px}a{color:#4493f8}
details{margin:0 0 8px}summary{cursor:pointer}
</style></head><body>
<nav>${views.map(([n], i) => `<button aria-pressed="${!i}" data-i="${i}">${n}</button>`).join('')}</nav>
${sections}
<script>
document.querySelectorAll('nav button').forEach(b=>b.onclick=()=>{
  document.querySelectorAll('nav button').forEach(x=>x.setAttribute('aria-pressed',x===b));
  document.querySelectorAll('section').forEach(s=>s.hidden=s.dataset.i!==b.dataset.i);
});
</script>
</body></html>
`;
}
